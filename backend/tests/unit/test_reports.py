"""
Unit tests for Excel Report Generator.
"""
import io
import pytest
from datetime import date
from sqlalchemy import create_engine
from sqlalchemy.orm import sessionmaker
from openpyxl import load_workbook

from app.db.base import Base
from app.models import Hotel, PriceRecommendations
from app.reports.generator import report_generator


@pytest.fixture
def db_session():
    engine = create_engine("sqlite:///:memory:", echo=False)
    Base.metadata.create_all(bind=engine)
    TestingSession = sessionmaker(bind=engine)
    session = TestingSession()
    try:
        yield session
    finally:
        session.close()


def test_generate_pricing_recommendations_excel(db_session):
    hotel = Hotel(hotel_code="HTL_RPT", hotel_name="Report Hotel", city="Goa")
    db_session.add(hotel)
    db_session.commit()

    stay_dt = date(2026, 10, 20)
    rec = PriceRecommendations(
        hotel_id=hotel.hotel_id,
        room_type_id=1,
        stay_date=stay_dt,
        recommended_rate=6200.0,
        min_rate=4500.0,
        max_rate=8000.0,
        current_rate=5000.0,
        occupancy=78.0,
        forecast_demand=90.0,
        competitor_median=6400.0,
        demand_index=1.24,
        price_reason="High demand",
        confidence_score=0.88,
        status="APPROVED",
    )
    db_session.add(rec)
    db_session.commit()

    excel_bytes = report_generator.generate_pricing_recommendations_excel(
        db_session, hotel_id=hotel.hotel_id, start_date=stay_dt, end_date=stay_dt
    )

    assert isinstance(excel_bytes, bytes)
    assert len(excel_bytes) > 0

    # Verify openpyxl can open generated bytes
    wb = load_workbook(io.BytesIO(excel_bytes))
    ws = wb.active
    assert ws.title == "Pricing Recommendations"
    assert ws.cell(row=1, column=1).value == "Stay Date"


def test_cute_orange_report_room_types(db_session):
    from app.models import RoomType
    hotel = Hotel(
        hotel_code="8485",
        hotel_name="Cute Orange Hotel",
        city="Chennai",
        min_price_floor=2800.0,
        max_price_ceiling=5000.0
    )
    db_session.add(hotel)
    db_session.commit()

    rt1 = RoomType(hotel_id=hotel.hotel_id, room_type_name="Standard Room", room_type_code="8485_STD", base_price=2800.0)
    rt2 = RoomType(hotel_id=hotel.hotel_id, room_type_name="Deluxe Room", room_type_code="8485_DLX", base_price=2800.0)
    db_session.add_all([rt1, rt2])
    db_session.commit()

    excel_bytes = report_generator.generate_pricing_recommendations_excel(
        db_session, hotel_id=hotel.hotel_id, start_date=date(2026, 9, 1), end_date=date(2026, 9, 7)
    )

    wb = load_workbook(io.BytesIO(excel_bytes))
    ws = wb.active
    room_types_found = set()
    for row in ws.iter_rows(min_row=2, values_only=True):
        room_types_found.add(row[1])

    assert room_types_found == {"Standard Room", "Deluxe Room"}
    assert "Executive Suite" not in room_types_found
    assert "Deluxe King" not in room_types_found

